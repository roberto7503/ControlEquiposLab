-- 2. Esquema requerido
CREATE SCHEMA IF NOT EXISTS inventario;

-- 3. Eliminar tablas previas si existen (respetando integridad referencial)
DROP TABLE IF EXISTS inventario.equipo CASCADE;
DROP TABLE IF EXISTS inventario.tipo_equipo CASCADE;

-- 4. Tabla: tipo_equipo
CREATE TABLE inventario.tipo_equipo (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(250)
);

-- 5. Tabla: equipo con restricciones CHECK, UNIQUE y FK
CREATE TABLE inventario.equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL,
    id_tipo BIGINT NOT NULL,
    CONSTRAINT fk_equipo_tipo_equipo FOREIGN KEY (id_tipo) REFERENCES inventario.tipo_equipo (id_tipo),
    CONSTRAINT chk_equipo_cantidad CHECK (cantidad >= 0),
    CONSTRAINT chk_equipo_estado CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio'))
);

